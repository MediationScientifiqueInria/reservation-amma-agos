create or replace function public.book_amma_slot(
  p_slot_id bigint,
  p_firstname text,
  p_lastname text,
  p_email text
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_token uuid;
  v_updated integer;
begin
  if nullif(trim(p_firstname), '') is null
     or nullif(trim(p_lastname), '') is null
     or nullif(trim(p_email), '') is null then
    raise exception 'missing_fields';
  end if;

  if lower(trim(p_email)) !~ '^[^@\s]+@inria\.fr$' then
    raise exception 'invalid_email_domain';
  end if;

  update public.amma_slots
     set booked = true
   where id = p_slot_id
     and booked = false
     and visible = true;

  get diagnostics v_updated = row_count;

  if v_updated <> 1 then
    raise exception 'slot_already_booked';
  end if;

  v_token := gen_random_uuid();

  insert into public.amma_bookings (
    slot_id,
    firstname,
    lastname,
    email,
    cancellation_token
  )
  values (
    p_slot_id,
    trim(p_firstname),
    trim(p_lastname),
    lower(trim(p_email)),
    v_token
  );

  return v_token;
end;
$$;

