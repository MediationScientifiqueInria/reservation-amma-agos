create or replace function public.admin_list_amma_reservations()
returns table (
  slot_id bigint,
  session_date date,
  start_time time,
  end_time time,
  visible boolean,
  booked boolean,
  booking_id bigint,
  firstname text,
  lastname text,
  email text,
  booked_at timestamptz,
  confirmation_email_sent_at timestamptz,
  pending_requests bigint
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_amma_admin() then
    raise exception 'admin_access_required';
  end if;

  return query
  select
    s.id as slot_id,
    s.session_date,
    s.start_time,
    s.end_time,
    s.visible,
    s.booked,
    b.id as booking_id,
    b.firstname,
    b.lastname,
    b.email,
    b.created_at as booked_at,
    b.confirmation_email_sent_at,
    coalesce(r.pending_requests, 0) as pending_requests
  from public.amma_slots s
  left join public.amma_bookings b
    on b.slot_id = s.id
  left join lateral (
    select count(*) as pending_requests
      from public.amma_booking_requests br
     where br.slot_id = s.id
       and br.confirmed_at is null
       and br.expires_at >= now()
  ) r on true
  order by s.session_date, s.start_time;
end;
$$;

create or replace function public.admin_list_amma_sessions()
returns table (
  session_date date,
  visible boolean,
  slots_count bigint,
  booked_count bigint,
  pending_requests bigint
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_amma_admin() then
    raise exception 'admin_access_required';
  end if;

  return query
  select
    s.session_date,
    bool_or(s.visible) as visible,
    count(*) as slots_count,
    count(*) filter (where s.booked) as booked_count,
    coalesce(sum(r.pending_requests), 0)::bigint as pending_requests
  from public.amma_slots s
  left join lateral (
    select count(*) as pending_requests
      from public.amma_booking_requests br
     where br.slot_id = s.id
       and br.confirmed_at is null
       and br.expires_at >= now()
  ) r on true
  group by s.session_date
  order by s.session_date;
end;
$$;

create or replace function public.admin_create_amma_session(
  p_session_date date,
  p_visible boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_inserted integer;
begin
  if not public.is_amma_admin() then
    raise exception 'admin_access_required';
  end if;

  if p_session_date is null then
    raise exception 'missing_session_date';
  end if;

  if exists (
    select 1
      from public.amma_slots
     where session_date = p_session_date
  ) then
    raise exception 'session_already_exists';
  end if;

  insert into public.amma_slots (session_date, start_time, end_time, visible)
  values
    (p_session_date, '11:30', '12:00', coalesce(p_visible, false)),
    (p_session_date, '12:00', '12:30', coalesce(p_visible, false)),
    (p_session_date, '12:30', '13:00', coalesce(p_visible, false)),
    (p_session_date, '13:10', '13:40', coalesce(p_visible, false)),
    (p_session_date, '13:40', '14:10', coalesce(p_visible, false));

  get diagnostics v_inserted = row_count;

  return jsonb_build_object(
    'created', true,
    'session_date', p_session_date,
    'visible', coalesce(p_visible, false),
    'created_slots', v_inserted
  );
end;
$$;

create or replace function public.admin_update_amma_session(
  p_current_session_date date,
  p_new_session_date date,
  p_visible boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_updated integer;
begin
  if not public.is_amma_admin() then
    raise exception 'admin_access_required';
  end if;

  if p_current_session_date is null or p_new_session_date is null then
    raise exception 'missing_session_date';
  end if;

  if not exists (
    select 1
      from public.amma_slots
     where session_date = p_current_session_date
  ) then
    raise exception 'session_not_found';
  end if;

  if p_current_session_date <> p_new_session_date then
    if exists (
      select 1
        from public.amma_slots
       where session_date = p_new_session_date
    ) then
      raise exception 'target_session_already_exists';
    end if;

    if exists (
      select 1
        from public.amma_bookings b
        join public.amma_slots s
          on s.id = b.slot_id
       where s.session_date = p_current_session_date
    ) then
      raise exception 'session_has_bookings';
    end if;

    if exists (
      select 1
        from public.amma_booking_requests r
        join public.amma_slots s
          on s.id = r.slot_id
       where s.session_date = p_current_session_date
         and r.confirmed_at is null
         and r.expires_at >= now()
    ) then
      raise exception 'session_has_pending_requests';
    end if;
  end if;

  update public.amma_slots
     set session_date = p_new_session_date,
         visible = coalesce(p_visible, false)
   where session_date = p_current_session_date;

  get diagnostics v_updated = row_count;

  return jsonb_build_object(
    'updated', true,
    'updated_slots', v_updated,
    'current_session_date', p_current_session_date,
    'new_session_date', p_new_session_date,
    'visible', coalesce(p_visible, false)
  );
end;
$$;

