create or replace function public.confirm_amma_booking_request(
  p_token uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.amma_booking_requests%rowtype;
  v_slot public.amma_slots%rowtype;
  v_cancellation_token uuid;
  v_updated integer;
begin
  select *
    into v_request
    from public.amma_booking_requests
   where confirmation_token = p_token
   for update;

  if v_request.id is null then
    raise exception 'request_not_found';
  end if;

  if v_request.confirmed_at is not null then
    raise exception 'request_already_confirmed';
  end if;

  if v_request.expires_at < now() then
    raise exception 'request_expired';
  end if;

  update public.amma_slots
     set booked = true
   where id = v_request.slot_id
     and booked = false
     and visible = true
   returning * into v_slot;

  get diagnostics v_updated = row_count;

  if v_updated <> 1 then
    raise exception 'slot_already_booked';
  end if;

  v_cancellation_token := gen_random_uuid();

  insert into public.amma_bookings (
    slot_id,
    firstname,
    lastname,
    email,
    cancellation_token
  )
  values (
    v_request.slot_id,
    v_request.firstname,
    v_request.lastname,
    v_request.email,
    v_cancellation_token
  );

  update public.amma_booking_requests
     set confirmed_at = now()
   where id = v_request.id;

  return jsonb_build_object(
    'cancellation_token', v_cancellation_token,
    'session_date', v_slot.session_date,
    'start_time', v_slot.start_time,
    'end_time', v_slot.end_time
  );
end;
$$;

drop function if exists public.cancel_amma_booking(uuid);

create or replace function public.cancel_amma_booking(
  p_token uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_booking record;
  v_email_token uuid;
begin
  select
    b.id,
    b.slot_id,
    b.firstname,
    b.lastname,
    b.email,
    s.session_date,
    s.start_time,
    s.end_time
    into v_booking
    from public.amma_bookings b
    join public.amma_slots s
      on s.id = b.slot_id
   where b.cancellation_token = p_token
   for update of b;

  if v_booking.id is null then
    return jsonb_build_object('cancelled', false);
  end if;

  delete from public.amma_bookings
   where id = v_booking.id;

  update public.amma_slots
     set booked = false
   where id = v_booking.slot_id;

  insert into public.amma_cancellations (
    slot_id,
    firstname,
    lastname,
    email,
    session_date,
    start_time,
    end_time
  )
  values (
    v_booking.slot_id,
    v_booking.firstname,
    v_booking.lastname,
    v_booking.email,
    v_booking.session_date,
    v_booking.start_time,
    v_booking.end_time
  )
  returning email_token into v_email_token;

  return jsonb_build_object(
    'cancelled', true,
    'cancellation_email_token', v_email_token
  );
end;
$$;

create or replace function public.is_amma_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1
      from public.amma_admins
     where email = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

