create or replace function public.admin_delete_amma_session(
  p_session_date date
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_deleted integer;
begin
  if not public.is_amma_admin() then
    raise exception 'admin_access_required';
  end if;

  if p_session_date is null then
    raise exception 'missing_session_date';
  end if;

  if not exists (
    select 1
      from public.amma_slots
     where session_date = p_session_date
  ) then
    raise exception 'session_not_found';
  end if;

  if exists (
    select 1
      from public.amma_bookings b
      join public.amma_slots s
        on s.id = b.slot_id
     where s.session_date = p_session_date
  ) then
    raise exception 'session_has_bookings';
  end if;

  if exists (
    select 1
      from public.amma_booking_requests r
      join public.amma_slots s
        on s.id = r.slot_id
     where s.session_date = p_session_date
       and r.confirmed_at is null
       and r.expires_at >= now()
  ) then
    raise exception 'session_has_pending_requests';
  end if;

  delete from public.amma_slots
   where session_date = p_session_date;

  get diagnostics v_deleted = row_count;

  return jsonb_build_object(
    'deleted', true,
    'session_date', p_session_date,
    'deleted_slots', v_deleted
  );
end;
$$;

